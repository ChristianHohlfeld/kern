#include "kern/game/builtin_meshes.h"

#include <cmath>
#include <memory>
#if !defined(__wasi__)
#include <mutex>
#endif
#include <unordered_map>

namespace kern::game {

namespace {

struct DuckMeshDef {
  const char* name;
  Vec3 lo, hi;  // bounds of the quantised positions (metres)
  u32 vertex_count, index_count;
  const short* pos;           // 16-bit over [lo, hi]
  const signed char* nrm;     // normal x 127
  const unsigned char* col;   // sRGB colour x 255
  const unsigned short* idx;
  u32 hull_count;
  const float* hull;
};

// Pollen Robotics' Micro Duck meshes (CC BY-NC-SA 4.0, non-commercial), generated by
// tools/micro_duck_import.py. A commercial build leaves them out (kern/build.sh --commercial,
// KERN_NO_NONCOMMERCIAL_ASSETS): the module then contains no Pollen 3D model and the duck's links
// have no look.
#if !defined(KERN_NO_NONCOMMERCIAL_ASSETS)
#include "../../third_party/microduck/micro_duck_meshes.inc"
#else
const DuckMeshDef kDuckMeshes[] = {{"", {}, {}, 0, 0, nullptr, nullptr, nullptr, nullptr, 0, nullptr}};
#endif

BuiltinMesh decode(const DuckMeshDef& d) {
  BuiltinMesh b;
  b.lo = d.lo;
  b.hi = d.hi;
  MeshData& m = b.mesh;
  m.positions.resize(static_cast<std::size_t>(d.vertex_count) * 3);
  m.normals.resize(m.positions.size());
  m.colors.resize(m.positions.size());
  m.uvs.assign(static_cast<std::size_t>(d.vertex_count) * 2, 0.0f);
  const f32 lo[3] = {d.lo.x, d.lo.y, d.lo.z}, span[3] = {d.hi.x - d.lo.x, d.hi.y - d.lo.y, d.hi.z - d.lo.z};
  for (std::size_t i = 0; i < m.positions.size(); ++i) {
    const int axis = static_cast<int>(i % 3);
    m.positions[i] = lo[axis] + (static_cast<f32>(d.pos[i]) + 32768.0f) / 65535.0f * span[axis];
    m.normals[i] = static_cast<f32>(d.nrm[i]) / 127.0f;
    m.colors[i] = static_cast<f32>(d.col[i]) / 255.0f;
  }
  for (std::size_t v = 0; v < d.vertex_count; ++v) {  // renormalise the 8-bit normals
    f32* n = &m.normals[v * 3];
    const f32 len = std::sqrt(n[0] * n[0] + n[1] * n[1] + n[2] * n[2]);
    if (len > 1e-6f) for (int k = 0; k < 3; ++k) n[k] /= len;
  }
  m.indices.assign(d.idx, d.idx + d.index_count);
  for (u32 i = 0; i < d.hull_count; ++i) b.hull.push_back({d.hull[i * 3], d.hull[i * 3 + 1], d.hull[i * 3 + 2]});
  return b;
}

}  // namespace

const BuiltinMesh* builtin_mesh(std::string_view name) {
  // The cache lives for the program. The Lehrer builds worlds on several threads at once: one at a time here.
  static std::unordered_map<std::string, std::unique_ptr<BuiltinMesh>> cache;
#if !defined(__wasi__)  // WebAssembly runs on one thread
  static std::mutex lock;
  const std::lock_guard<std::mutex> guard(lock);
#endif
  const std::string key(name);
  if (auto it = cache.find(key); it != cache.end()) return it->second.get();
  for (const DuckMeshDef& d : kDuckMeshes)
    if (d.vertex_count && key == d.name) return (cache[key] = std::make_unique<BuiltinMesh>(decode(d))).get();
  return nullptr;
}

std::vector<std::string> builtin_mesh_names() {
  std::vector<std::string> out;
  for (const DuckMeshDef& d : kDuckMeshes)
    if (d.vertex_count) out.push_back(d.name);
  return out;
}

}  // namespace kern::game
