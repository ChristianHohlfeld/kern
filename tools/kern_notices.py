#!/usr/bin/env python3
"""Writes the licence notices every copy of Kern carries into kern/web/kern.mjs (KERN_NOTICES).

    python3 -I tools/kern_notices.py [--check]

kern.mjs is part of the Studio page and of every game Studio exports, so the notices travel with
the engine: Kern's NOTICE and Apache License 2.0, the MIT texts of Box3D and musl and Earcut's ISC
text (kern/LICENSES.md). Exported games also start with them as an HTML comment (game.mjs).
--check fails if kern.mjs is out of date.
"""
import json
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
BEGIN = "// ---- licence notices: generated by tools/kern_notices.py, do not edit ----\n"
END = "// ---- end of licence notices ----\n"


def notices():
    lic = (root / "kern/LICENSES.md").read_text()
    isc = re.search(r"## Earcut.*?```\n(.*?)```", lic, re.S).group(1)
    musl = (root / "kern/third_party/musl_math/COPYRIGHT").read_text()
    musl = musl.split("-" * 70)[1].strip() + "\n"
    parts = [
        (root / "NOTICE").read_text(),
        "Kern: " + (root / "LICENSE").read_text(),
        "Box3D:\n" + (root / "kern/third_party/box3d/LICENSE").read_text(),
        "musl:\n" + musl,
        "Earcut:\n" + isc,
        "Intel XeGTAO:\n" + (root / "kern/third_party/xegtao/LICENSE").read_text(),
        "three.js:\n" + (root / "kern/third_party/threejs/LICENSE").read_text(),
    ]
    return "\n" + ("\n" + "=" * 72 + "\n").join(p.strip("\n") + "\n" for p in parts)


def main():
    path = root / "kern/web/kern.mjs"
    src = path.read_text()
    block = BEGIN + "export const KERN_NOTICES = " + json.dumps(notices(), ensure_ascii=False) + ";\n" + END
    if BEGIN in src:
        a, b = src.index(BEGIN), src.index(END) + len(END)
        new = src[:a] + block + src[b:]
    else:
        anchor = 'export const KERN_WEB_VERSION = "kern-web-1";\n'
        new = src.replace(anchor, anchor + "\n" + block, 1)
    if "--check" in sys.argv:
        if new != src:
            sys.exit("kern/web/kern.mjs: licence notices out of date (run python3 -I tools/kern_notices.py)")
        return
    path.write_text(new)
    print("updated", path)


if __name__ == "__main__":
    main()
